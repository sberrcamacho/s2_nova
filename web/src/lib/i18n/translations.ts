// The app language for code outside React (formatters, copy helpers, the
// category registry). AuthProvider keeps it in step with the user's
// preference before its children render; components use useTranslation().
let current: LanguageCode = "es";

export function currentLanguage(): LanguageCode {
  return current;
}

export function setCurrentLanguage(language: LanguageCode) {
  current = language;
}

export function tr(key: TranslationKey): string {
  return dictionary[key][current];
}

// "{0} de {1}" → fill(tr(key), a, b).
export function fill(template: string, ...values: (string | number)[]): string {
  return template.replace(/\{(\d+)\}/g, (_, i) => String(values[Number(i)] ?? ""));
}

