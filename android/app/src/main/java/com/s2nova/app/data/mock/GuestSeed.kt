// The guest account shared with Web (assets/guest_seed.json, generated by
// scripts/gen-guest-seed.mjs; never edit it by hand). Its relative dates are
// resolved against today when the guest session starts, and everything else
// (balances, budget spending, goal progress, Programado and plan counts,
// settled loans, alerts) is derived from the movements dated up to today,
// with the same rules Web's guestApi.ts and the backend use.

